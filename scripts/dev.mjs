import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  copyFileSync,
  existsSync,
  readdirSync,
  watch,
} from "node:fs";
import { execFile, execFileSync } from "node:child_process";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { SOURCE_PARTS } from "./source-order.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const hasFlag = (name) => args.includes(name);
const argValue = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

function readJson(file) {
  return JSON.parse(readFileSync(path.join(root, file), "utf8"));
}

function getAppDataDir() {
  switch (process.platform) {
    case "darwin":
      return path.join(os.homedir(), "Library", "Application Support");
    case "win32":
      return process.env.APPDATA || path.join(os.homedir(), "AppData", "Roaming");
    default:
      return process.env.XDG_DATA_HOME || path.join(os.homedir(), ".local", "share");
  }
}

function openUrl(url) {
  const [command, commandArgs] =
    process.platform === "darwin" ? ["open", [url]]
    : process.platform === "win32" ? ["cmd", ["/c", "start", "", url]]
    : ["xdg-open", [url]];
  execFile(command, commandArgs, () => {});
}

function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else copyFileSync(from, to);
  }
}

function buildBundle(version) {
  const versionLine = "  var __LTE_VERSION__ = " + JSON.stringify(version) + ";\n";
  const inner = versionLine + SOURCE_PARTS.map((rel) =>
    readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n")
  ).join("");
  const code = "/* Generated by scripts/dev.mjs. Do not edit the installed copy directly. */\n" + "(function() {\n" + inner + "\n})();\n";
  if (!code.includes("window.registerExtension")) {
    throw new Error("bundle is missing window.registerExtension");
  }
  return code;
}

function main() {
  const manifest = readJson("sjmcl.ext.json");
  const identifier = manifest.identifier;
  if (!/^[a-z][a-z0-9_-]*(\.[a-z][a-z0-9_-]*)+$/.test(identifier)) {
    throw new Error("invalid extension identifier: " + identifier);
  }

  const targetDir = argValue("--path")
    ? path.resolve(argValue("--path"))
    : path.join(getAppDataDir(), "SJMCL", "UserContent", "Extensions", identifier);
  const noReload = hasFlag("--no-reload");

  let timer = null;
  let building = false;
  let queued = false;

  function build() {
    if (building) {
      queued = true;
      return;
    }
    building = true;
    try {
      const code = buildBundle(manifest.version);
      mkdirSync(path.join(targetDir, "frontend"), { recursive: true });
      const frontendPath = path.join(targetDir, "frontend", "index.js");
      writeFileSync(frontendPath, code, "utf8");
      execFileSync(process.execPath, ["--check", frontendPath], { stdio: "pipe" });

      writeFileSync(path.join(targetDir, "sjmcl.ext.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");
      const icon = path.join(root, "icon.png");
      if (existsSync(icon)) copyFileSync(icon, path.join(targetDir, "icon.png"));
      for (const dir of ["assets", "data"]) {
        const src = path.join(root, dir);
        if (existsSync(src)) copyDir(src, path.join(targetDir, dir));
      }

      console.log("[dev] built -> " + targetDir);
      if (!noReload) {
        const deeplink = "sjmcl://reload-extension?id=" + identifier;
        openUrl(deeplink);
        console.log("[dev] reload: " + deeplink);
      }
    } catch (error) {
      console.error("[dev] build failed: " + (error && error.message ? error.message : error));
    } finally {
      building = false;
      if (queued) {
        queued = false;
        schedule();
      }
    }
  }

  function schedule() {
    if (timer) clearTimeout(timer);
    timer = setTimeout(build, 150);
  }

  build();
  for (const rel of SOURCE_PARTS) {
    watch(path.join(root, rel), { persistent: true }, schedule);
  }
  console.log("[dev] watching " + SOURCE_PARTS.length + " source parts");
  console.log('[dev] enable "' + identifier + '" in SJMCL Settings > Extensions first');
}

try {
  main();
} catch (error) {
  console.error("[dev] failed: " + (error && error.message ? error.message : error));
  process.exitCode = 1;
}
