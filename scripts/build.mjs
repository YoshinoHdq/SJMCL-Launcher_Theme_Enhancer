import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
  copyFileSync,
  existsSync,
  readdirSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { zipSync } from "fflate";
import { SOURCE_PARTS } from "./source-order.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function readJson(file) {
  return JSON.parse(readFileSync(path.join(root, file), "utf8"));
}

function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else copyFileSync(from, to);
  }
}

const GENERATED_BANNER = "/* Generated by scripts/build.mjs. Do not edit frontend/index.js directly. */\n";

function localeKeys(file) {
  const text = readFileSync(path.join(root, file), "utf8");
  const keys = [...text.matchAll(/^\s{4}([A-Za-z0-9_]+):/gm)].map((match) => match[1]);
  const duplicates = [...new Set(keys.filter((key, index) => keys.indexOf(key) !== index))];
  if (duplicates.length > 0) {
    throw new Error("duplicate locale keys in " + file + ": " + duplicates.join(", "));
  }
  return keys;
}

function validateLocales() {
  const en = localeKeys("src/locales/en.ts");
  const zh = localeKeys("src/locales/zh.ts");
  const typeText = readFileSync(path.join(root, "src/locales/types.ts"), "utf8");
  const declared = [...typeText.matchAll(/^\s{2}([A-Za-z0-9_]+):/gm)].map((match) => match[1]);
  const missingZh = en.filter((key) => !zh.includes(key));
  const missingEn = zh.filter((key) => !en.includes(key));
  const missingTypes = en.filter((key) => !declared.includes(key));
  const extraTypes = declared.filter((key) => !en.includes(key));
  if (missingZh.length || missingEn.length || missingTypes.length || extraTypes.length) {
    throw new Error(
      "locale key mismatch: missing zh=[" + missingZh.join(",") + "] missing en=[" + missingEn.join(",") +
      "] missing types=[" + missingTypes.join(",") + "] extra types=[" + extraTypes.join(",") + "]"
    );
  }
}

function buildBundle(version) {
  const versionLine = "  var __LTE_VERSION__ = " + JSON.stringify(version) + ";\n";
  const inner = versionLine + SOURCE_PARTS.map((rel) =>
    readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n")
  ).join("");

  const code = GENERATED_BANNER + "(function() {\n" + inner + "\n})();\n";
  if (!code.includes("window.registerExtension")) {
    throw new Error("bundle is missing window.registerExtension");
  }
  return code;
}

function copyStatics(targetDir, manifest) {
  writeFileSync(path.join(targetDir, "sjmcl.ext.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");

  const icon = path.join(root, "icon.png");
  if (existsSync(icon)) copyFileSync(icon, path.join(targetDir, "icon.png"));

  for (const dir of ["assets", "data"]) {
    const src = path.join(root, dir);
    if (existsSync(src)) copyDir(src, path.join(targetDir, dir));
  }
}

function collectEntries(baseDir, prefix, entries) {
  for (const entry of readdirSync(baseDir, { withFileTypes: true })) {
    const full = path.join(baseDir, entry.name);
    const rel = prefix ? prefix + "/" + entry.name : entry.name;
    if (entry.isDirectory()) collectEntries(full, rel, entries);
    else entries[rel] = new Uint8Array(readFileSync(full));
  }
}

function packageExtension(pkgDir, manifest, isDev) {
  const suffix = isDev ? "-dev" : "";
  const archiveName = manifest.identifier + "-" + manifest.version + suffix + ".sjmclx";
  const archivePath = path.join(root, "dist", archiveName);
  const entries = {};
  collectEntries(pkgDir, manifest.identifier, entries);
  writeFileSync(archivePath, zipSync(entries, { level: 9 }));
  return archivePath;
}

function main() {
  const isDev = process.argv.includes("--dev");
  const manifest = readJson("sjmcl.ext.json");
  const pkgDir = path.join(root, "dist", manifest.identifier);

  validateLocales();
  const code = buildBundle(manifest.version);
  const frontendPath = path.join(root, "frontend", "index.js");
  writeFileSync(frontendPath, code, "utf8");
  execFileSync(process.execPath, ["--check", frontendPath], { stdio: "pipe" });

  rmSync(pkgDir, { recursive: true, force: true });
  mkdirSync(path.join(pkgDir, "frontend"), { recursive: true });
  writeFileSync(path.join(pkgDir, "frontend", "index.js"), code, "utf8");
  copyStatics(pkgDir, manifest);

  const archivePath = packageExtension(pkgDir, manifest, isDev);
  console.log("Built  " + pkgDir);
  console.log("Packed " + archivePath);
}

try {
  main();
} catch (error) {
  console.error("Build failed: " + (error && error.message ? error.message : error));
  process.exitCode = 1;
}
